def payload(book: "Book", report: Optional["Report"] = None,
            page: Optional[int] = None, dpi: int = 150) -> dict[str, Any]:
    """Everything a UI needs: book info, outline, items, flags, page text."""
    info = book.info()
    pages = book.pages if page is None else [book.page(page)]
    flags_by_page: dict[int, list["Flag"]] = {}
    if report is not None:
        for f in report.flags:
            flags_by_page.setdefault(f.page, []).append(f)
    return {
        "bookkit": __version__,
        "info": info,
        "pages": [
            {
                "number": p.number,
                "width": p.width,
                "height": p.height,
                "chars": p.chars,
                "raster": p.raster,
                "raster_px": list(p.raster_px),
                "header": p.header,
                "folio": p.folio,
                "paragraphs": [par.to_dict() for par in p.paragraphs],
                "lines": [
                    {"i": l.index, "text": l.text, "bbox": [round(v, 1) for v in l.bbox],
                     "junk": l.junk}
                    for l in p.lines
                ],
                "flags": [f.to_dict() for f in flags_by_page.get(p.number, [])],
            }
            for p in pages
        ],
        "outline": [e.to_dict() for e in structure.outline(book)],
        "sections": structure.sections(book),
        "items": [it.to_dict(text=False) for it in structure.items(book)],
        "ocr": report.summary() if report else None,
        "render_dpi": dpi,
    }
