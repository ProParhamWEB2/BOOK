@dataclass
class Chunk:
    id: str
    text: str
    page: int
    end_page: int
    role: str
    section: Optional[str] = None
    section_number: Optional[str] = None
    number: Optional[str] = None
    bbox: tuple[float, float, float, float] = (0.0, 0.0, 0.0, 0.0)
    lines: list[int] = field(default_factory=list)
    flags: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        d: dict[str, Any] = {
            "id": self.id,
            "page": self.page,
            "end_page": self.end_page,
            "role": self.role,
            "text": self.text,
            "lines": self.lines,
            "bbox": [round(v, 1) for v in self.bbox],
        }
        if self.section:
            d["section"] = self.section
        if self.section_number:
            d["section_number"] = self.section_number
        if self.number:
            d["number"] = self.number
        if self.flags:
            d["flags"] = self.flags
        return d


def chunks(book: "Book", report: Optional["Report"] = None,
           merge_items: bool = True) -> list[Chunk]:
    """Paragraph-level chunks, with problems/exercises merged into one chunk."""
    items = structure.items(book) if merge_items else []
    # paragraph identity -> the item it belongs to
    item_text: dict[int, Any] = {}
    for it in items:
        for p in it.paragraphs:
            item_text[id(p)] = it
    emitted: set[int] = set()

    flags_by_page: dict[int, list["Flag"]] = {}
    if report is not None:
        for f in report.flags:
            flags_by_page.setdefault(f.page, []).append(f)

    out: list[Chunk] = []
    for page in book.pages:
        for par in page.paragraphs:
            if par.role == structure.ROLE_NOISE:
                continue
            it = item_text.get(id(par))
            if it is not None and merge_items:
                if id(it) in emitted:
                    continue  # only the first paragraph emits the merged chunk
                emitted.add(id(it))
                number = it.number or str(len(out))
                cid = f"p{it.page}:{it.kind}:{number}"
                flags = [f.code for f in flags_by_page.get(it.page, [])
                         if f.line in set(it.line_numbers())]
                out.append(Chunk(
                    id=cid, text=it.text, page=it.page, end_page=it.end_page,
                    role=it.kind, section=it.section, section_number=it.section_number,
                    number=it.number, bbox=it.bbox, lines=it.line_numbers(),
                    flags=sorted(set(flags)),
                ))
                continue
            flags = [f.code for f in flags_by_page.get(page.number, []) if f.line in par.line_numbers()]
            out.append(Chunk(
                id=f"p{page.number}:{par.role}:{par.line_numbers()[0] if par.lines else 0}",
                text=par.text, page=page.number, end_page=page.number, role=par.role,
                bbox=par.bbox, lines=par.line_numbers(), flags=sorted(set(flags)),
            ))
    return out


def chunks_jsonl(book: "Book", report: Optional["Report"] = None) -> str:
    return "\n".join(json.dumps(c.to_dict(), ensure_ascii=False) for c in chunks(book, report)) + "\n"


