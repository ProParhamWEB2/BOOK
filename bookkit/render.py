"""bookkit.render — turn the model into Markdown, JSONL, digests and payloads.

Three output shapes, three consumers:

* **Markdown** — a human (or an LLM) reads the chapter; page anchors live in
  HTML comments so the file stays clean but stays traceable.
* **JSONL** — retrieval-friendly chunks with page/section/role metadata and
  the OCR flags attached, ready for embedding or grep.
* **Digest** — a *context-window-friendly* map of the book: per page, what is
  there, what is broken, what needs eyes.  This is what an agent reads first.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any, Iterable, Optional, Sequence

from . import __version__, structure

if TYPE_CHECKING:  # pragma: no cover
    from .core import Book, Page, Paragraph
    from .quality import Flag, Report

MATHISH = re.compile(
    r"(?:\d+\s*[+\-*/×÷=]\s*\d+|\\frac|\\sum|\\int|\^\s*\d|[a-z]\s*=\s*[-0-9]|"
    r"\b(?:mod|gcd|lcm)\b|∑|∫|≤|≥|≠)", re.I)
OPERATORS = re.compile(r"[=+\-*/×÷^<>√∑∫≤≥≠]")
WORDISH = re.compile(r"[A-Za-z]{3,}")


def is_mathish(text: str) -> bool:
    """Heuristic: a short line with operators and few words is probably maths."""
    if len(text) > 200:
        return False
    ops = OPERATORS.findall(text)
    words = WORDISH.findall(text)
    digits = sum(ch.isdigit() for ch in text)
    return (len(ops) >= 2 and digits >= 1 and len(words) <= 4) or \
        (bool(MATHISH.search(text)) and len(words) <= 3)


def _fence(text: str) -> str:
    """Wrap probable maths so a reader/LLM does not 'fix' it as prose."""
    return "`" + text.strip() + "`" if is_mathish(text) else text


