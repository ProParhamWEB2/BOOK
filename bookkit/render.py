def digest(book: "Book", report: Optional["Report"] = None, per_page: int = 220,
           include_clean: bool = False) -> dict[str, Any]:
    """A compact map of the book for a limited context window."""
    info = book.info()
    items = structure.items(book)
    by_page: dict[int, list[structure.Item]] = {}
    for it in items:
        by_page.setdefault(it.page, []).append(it)
    flags_by_page: dict[int, list["Flag"]] = {}
    if report is not None:
        for f in report.flags:
            flags_by_page.setdefault(f.page, []).append(f)

    sections = structure.sections(book)
    pages: list[dict[str, Any]] = []
    for page in book.pages:
        page_flags = flags_by_page.get(page.number, [])
        pr = None
        if report is not None:
            pr = next((p for p in report.pages if p.number == page.number), None)
        verdict = pr.verdict if pr else "unknown"
        if verdict == "clean" and not include_clean and not page_flags and not by_page.get(page.number):
            continue
        # the *most specific* section wins: "1.2 Counting Lists of Numbers",
        # not the enclosing "CHAPTER 1"
        covering = [s for s in sections
                    if s["page"] <= page.number <= s.get("end_page", s["page"])]
        sec = max(covering, key=lambda s: s["level"]) if covering else None
        pages.append({
            "page": page.number,
            "verdict": verdict,
            "score": pr.score if pr else 0.0,
            "section": sec["title"] if sec else None,
            "chars": page.chars,
            "items": [
                {"id": it.id, "tag": it.tag, "in_box": it.in_box,
                 "duplicate_of": it.duplicate_of, "hints": it.hints}
                for it in by_page.get(page.number, [])
            ],
            "flags": sorted({f.code for f in page_flags}),
            "preview": (page.text[:per_page] + "…") if len(page.text) > per_page else page.text,
        })
    return {
        "bookkit": __version__,
        "path": info["path"],
        "pages": info["pages"],
        "title": info.get("title") or _guess_title(book),
        "reading_size": report.reading_size if report else None,
        "outline": [e.to_dict() for e in structure.outline(book)][:240],
        "sections": sections,
        "item_counts": _count_kinds(items),
        "ocr": report.summary() if report else None,
        "digest_pages": pages,
    }


def _count_kinds(items: Sequence[structure.Item]) -> dict[str, int]:
    out: dict[str, int] = {}
    for it in items:
        out[it.kind] = out.get(it.kind, 0) + 1
    return out


def digest_text(book: "Book", report: Optional["Report"] = None, per_page: int = 200) -> str:
    d = digest(book, report, per_page=per_page)
    out = [
        f"# {d['title'] or d['path']}",
        f"pages={d['pages']} items={d['item_counts']}",
        "",
        "## outline",
    ]
    for e in d["outline"]:
        out.append(f"{'  ' * max(0, e['level'] - 1)}- [{e['level']}] {e['title']} (p{e['page']})")
    if d["ocr"]:
        o = d["ocr"]
        out.append("")
        out.append(f"## ocr: score={o['score']} verdicts={o['verdicts']} flags={o['flag_counts']}")
    out.append("")
    out.append("## pages (non-clean only)")
    for p in d["digest_pages"]:
        head = f"p{p['page']} [{p['verdict']}]"
        if p["section"]:
            head += f" §{p['section']}"
        if p["items"]:
            head += " items:" + ",".join(i["id"] for i in p["items"])
        if p["flags"]:
            head += " ⚠" + ",".join(p["flags"])
        out.append(head)
        out.append("   " + p["preview"].replace("\n", " ")[:per_page])
    return "\n".join(out)


