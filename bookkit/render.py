@dataclass
class MarkdownOptions:
    title: Any = None                 # override the book title
    page_breaks: bool = True          # HTML comment markers per page
    include_flags: bool = True        # inline warnings for suspicious lines
    include_outline: bool = True      # table of contents at the top
    drop_furniture: bool = True       # running heads/folios already removed
    heading_prefix: str = ""
    max_heading_level: int = 4


def _md_escape(text: str) -> str:
    return text.replace("<", "&lt;").replace(">", "&gt;")


def to_markdown(book: "Book", report: Optional["Report"] = None,
                opts: MarkdownOptions | None = None) -> str:
    opts = opts or MarkdownOptions()
    out: list[str] = []
    info = book.info()
    title = opts.title or info.get("title") or _guess_title(book) or book.path.stem
    out.append(f"# {title}")
    out.append("")
    src = book.path.name
    bits = [f"pages: {info['pages']}", f"source: `{src}`"]
    if info.get("author"):
        bits.append(f"author: {info['author']}")
    if info.get("scanned_pages"):
        bits.append("scanned/OCR text layer")
    out.append(" ".join(f"*{b}*" for b in bits))
    out.append("")

    if opts.include_outline:
        entries = structure.outline(book)
        if entries:
            out.append("## Outline")
            out.append("")
            for e in entries:
                if e.level > opts.max_heading_level:
                    continue
                pad = "  " * max(0, e.level - 1)
                out.append(f"{pad}- {e.title}  *(p{e.page})*")
            out.append("")

    flag_index: dict[int, list["Flag"]] = {}
    if report is not None and opts.include_flags:
        for f in report.flags:
            if f.line is not None:
                flag_index.setdefault(f.page, []).append(f)

    # problems/exercises are re-flowed from their merged form, so a statement
    # split across lines by the scanner is rendered as the single unit it is
    merged: dict[int, list[structure.Item]] = {}
    for it in structure.items(book):
        merged.setdefault(id(it.paragraphs[0]), []).append(it)
    consumed: set[int] = set()

    for page in book.pages:
        if opts.page_breaks:
            out.append(f"<!-- bookkit:page={page.number} -->")
        page_flags = flag_index.get(page.number, [])
        for par in page.paragraphs:
            items_here = merged.get(id(par))
            if items_here:
                it = items_here[0]
                for member in it.paragraphs:
                    consumed.add(id(member))
                out.extend(_render_item(it, page_flags, opts))
                continue
            if id(par) in consumed:
                continue
            out.extend(_render_paragraph(par, page_flags, opts))
        out.append("")

    out.append("")
    out.append(f"<!-- generated by bookkit {__version__} -->")
    return "\n".join(_compact_blank(out))


def _guess_title(book: "Book") -> str:
    entries = structure.outline(book)
    for e in entries:
        if e.level == 0:
            return e.title.strip()
    for e in entries:
        if e.level == 1:
            return e.title.strip()
    return ""


def _render_item(it: structure.Item, flags: Sequence["Flag"],
                 opts: MarkdownOptions) -> list[str]:
    """Render a merged problem/exercise/solution as one Markdown block."""
    from .core import Paragraph  # local: keeps the module import-light

    lines_n = it.line_numbers()
    my_flags = [f for f in flags if f.line in lines_n]
    warn = ""
    if my_flags and opts.include_flags:
        codes = ", ".join(sorted({f.code for f in my_flags}))
        warn = f" <!-- ⚠ OCR {codes} @p{it.page} -->"

    text = it.text.strip()
    if it.kind == "problem":
        return [f"> **{text}**{warn}", ""]
    if it.kind == "solution":
        return [f"**Solution** — {_fence(text)}{warn}", ""]
    if it.kind == "exercise":
        num = it.number or ""
        body = text
        if num and body.startswith(num):
            body = body[len(num):].lstrip("★* ").strip()
        star = "★ " if it.star else ""
        suffix = ""
        if it.hints:
            suffix = f"  *(hints: {', '.join(it.hints)})*"
        return [f"- **{star}{num}** {_fence(body)}{suffix}{warn}"]
    if it.kind == "example":
        return [f"**Example** — {_fence(text)}{warn}", ""]
    return [f"> {_fence(text)}{warn}", ""]


def _render_paragraph(par: "Paragraph", flags: Sequence["Flag"],
                      opts: MarkdownOptions) -> list[str]:
    text = par.text.strip()
    if not text:
        return []
    lines: list[str] = []
    tag = f"p{par.page_no}"
    my_flags = [f for f in flags if f.text and f.text.strip() == text]
    warn = ""
    if my_flags:
        codes = ", ".join(sorted({f"{f.code}" for f in my_flags}))
        warn = f" <!-- ⚠ OCR {codes} @{tag} -->"

    if par.role == structure.ROLE_HEADING:
        level = par.level if par.level is not None else 2
        level = max(1, min(level + 1, 6))  # bookkit level 0 -> "#"
        if par.level == 0:
            level = 1
        lines.append(f"{'#' * level} {text}")
        lines.append("")
    elif par.role == structure.ROLE_PROBLEM:
        lines.append(f"> **{text}**{warn}")
        lines.append("")
    elif par.role == structure.ROLE_SOLUTION:
        lines.append(f"**Solution** — {_fence(text)}{warn}")
        lines.append("")
    elif par.role == structure.ROLE_EXERCISE:
        body = text
        num = par.number or ""
        if num and body.startswith(num):
            body = body[len(num):].lstrip("* ").strip()
        star = "★ " if par.attrs.get("star") else ""
        lines.append(f"- **{star}{num}** {_fence(body)}{warn}")
    elif par.role == structure.ROLE_LABEL:
        lines.append(f"**{text}**{warn}")
        lines.append("")
    elif par.role == structure.ROLE_EXAMPLE:
        lines.append(f"**Example** — {_fence(text)}{warn}")
        lines.append("")
    elif par.role == structure.ROLE_THEOREM:
        lines.append(f"> {_fence(text)}{warn}")
        lines.append("")
    elif par.role == structure.ROLE_NOISE:
        return []
    else:
        body = _fence(text)
        if par.attrs.get("in_box"):
            lines.append(f"> {body}{warn}")
        else:
            lines.append(f"{body}{warn}")
        lines.append("")
    return lines


def _compact_blank(lines: Sequence[str]) -> list[str]:
    out: list[str] = []
    for ln in lines:
        if ln == "" and out and out[-1] == "":
            continue
        out.append(ln)
    return out


