def rtl(s):
    return get_display(arabic_reshaper.reshape(str(s)))

def measure(s, font, size):
    return pdfmetrics.stringWidth(s, font, size)

def wrap_rtl(text, font, size, width):
    # Preserve deliberate line breaks, and keep each natural Persian word together.
    out=[]
    for para in str(text).split('\n'):
        if not para.strip():
            out.append(''); continue
        words=para.split()
        line=''
        for word in words:
            trial = (line+' '+word).strip()
            if measure(rtl(trial), font, size) <= width or not line:
                line=trial
            else:
                out.append(line); line=word
        if line: out.append(line)
    return out

def wrap_ltr(text, font, size, width):
    out=[]
    for para in str(text).split('\n'):
        if not para.strip(): out.append(''); continue
        words=para.split(); line=''
        for word in words:
            trial=(line+' '+word).strip()
            if measure(trial,font,size)<=width or not line: line=trial
            else: out.append(line); line=word
        if line: out.append(line)
    return out

class Page:
    def __init__(self, c, num, section='شمارش همان حساب است'):
        self.c=c; self.num=num; self.section=section; self.y=H-58
        c.setFillColor(INK)
        c.setStrokeColor(INK)
        c.setLineWidth(.7)
        c.line(MARGIN_L, H-36, W-MARGIN_R, H-36)
        c.setFont(FONT_SANS_B, 7.0)
        c.drawRightString(W-MARGIN_R, H-29, rtl(f'فصل ۱  |  {section}'))
        c.setFont(FONT_SANS, 7.1)
        c.drawString(MARGIN_L, 20, str(num))
    def need(self, n):
        if self.y-n < 37:
            print('LOW PAGE', self.num, self.y, n)
    def gap(self, n=7): self.y-=n
    def rtl(self, text, size=9.2, leading=None, bold=False, width=CONTENT_W, color=INK, bullet=None):
        font=FONT_B if bold else FONT_R
        if leading is None: leading=size*1.48
        if bullet:
            # reserve room for a small bullet on the right
            width -= 18
        lines=wrap_rtl(text,font,size,width)
        self.need(len(lines)*leading)
        self.c.setFillColor(color); self.c.setFont(font,size)
        for line in lines:
            self.c.drawRightString(W-MARGIN_R-(18 if bullet else 0), self.y, rtl(line))
            if bullet:
                self.c.setFillColor(NAVY); self.c.circle(W-MARGIN_R-5, self.y+size*.28, 2.1, fill=1, stroke=0); self.c.setFillColor(color)
            self.y -= leading
        return len(lines)*leading
    def ltr(self, text, size=9.2, leading=None, bold=False, width=CONTENT_W, align='left', color=INK):
        font=FONT_B if bold else FONT_R
        if leading is None: leading=size*1.45
        lines=wrap_ltr(text,font,size,width)
        self.need(len(lines)*leading)
        self.c.setFillColor(color); self.c.setFont(font,size)
        x=MARGIN_L if align=='left' else W-MARGIN_R
        for line in lines:
            if align=='center': self.c.drawCentredString(W/2,self.y,line)
            elif align=='right': self.c.drawRightString(W-MARGIN_R,self.y,line)
            else: self.c.drawString(MARGIN_L,self.y,line)
            self.y-=leading
        return len(lines)*leading
    def formula(self, text, size=10.0, gap_after=7, color=NAVY):
        self.need(size*1.7+gap_after); self.c.setFillColor(color); self.c.setFont(FONT_SANS_B,size)
        self.c.drawCentredString(W/2, self.y, text); self.y -= size*1.5+gap_after
    def heading(self, text, size=13, color=NAVY):
        self.need(28); self.c.setFillColor(color); self.c.setFont(FONT_B,size)
        self.c.drawRightString(W-MARGIN_R,self.y,rtl(text)); self.y -= size*1.55
        self.c.setStrokeColor(GOLD); self.c.setLineWidth(1.1); self.c.line(MARGIN_L,self.y+4,W-MARGIN_R,self.y+4); self.c.setStrokeColor(INK)
        self.y -= 5
    def subheading(self, text):
        self.need(20); self.c.setFillColor(NAVY); self.c.setFont(FONT_B,10.7); self.c.drawRightString(W-MARGIN_R,self.y,rtl(text)); self.y-=16
    def problem(self, num, text, size=8.7, fill=True, gap_after=5):
        lines=wrap_rtl(text,FONT_R,size,CONTENT_W-55)
        h=max(25, len(lines)*size*1.42+15)
        self.need(h)
        if fill:
            self.c.setFillColor(PALE2); self.c.roundRect(MARGIN_L,self.y-h+3,CONTENT_W,h,4,fill=1,stroke=0)
            self.c.setStrokeColor(colors.HexColor('#cad7e1')); self.c.roundRect(MARGIN_L,self.y-h+3,CONTENT_W,h,4,fill=0,stroke=1)
        self.c.setFillColor(NAVY); self.c.setFont(FONT_SANS_B, size+0.1); self.c.drawString(MARGIN_L+9,self.y-2,f'{num}')
        self.c.setFillColor(INK); self.c.setFont(FONT_R,size)
        yy=self.y-2
        for line in lines:
            self.c.drawRightString(W-MARGIN_R-10,yy,rtl(line)); yy-=size*1.42
        self.y-=h+gap_after
    def exercise(self, num, text, size=8.6, gap_after=4):
        lines=wrap_rtl(text,FONT_R,size,CONTENT_W-42)
        self.need(len(lines)*size*1.42+3)
        self.c.setFillColor(NAVY); self.c.setFont(FONT_SANS_B,size+0.1); self.c.drawString(MARGIN_L,self.y,f'{num}')
        self.c.setFillColor(INK); self.c.setFont(FONT_R,size)
        yy=self.y
        for line in lines:
            self.c.drawRightString(W-MARGIN_R,yy,rtl(line)); yy-=size*1.42
        self.y=yy-gap_after
    def callout(self, label, text, kind='important'):
        h=38 if len(text)<75 else 50
        self.need(h+8)
        col=colors.HexColor('#fff5dc') if kind=='important' else colors.HexColor('#f8e9e9')
        edge=GOLD if kind=='important' else colors.HexColor('#a54545')
        self.c.setFillColor(col); self.c.setStrokeColor(edge); self.c.setLineWidth(.8)
        self.c.roundRect(MARGIN_L,self.y-h+5,CONTENT_W,h,5,fill=1,stroke=1)
        self.c.setFillColor(edge); self.c.setFont(FONT_B,9.2); self.c.drawRightString(W-MARGIN_R-10,self.y-10,rtl(label))
        self.c.setFillColor(INK); self.c.setFont(FONT_R,8.7)
        lines=wrap_rtl(text,FONT_R,8.7,CONTENT_W-120)
        yy=self.y-10
        for line in lines:
            self.c.drawRightString(W-MARGIN_R-94,yy,rtl(line)); yy-=12
        self.y-=h+8
    def caption(self, text):
        self.c.setFillColor(colors.HexColor('#526675')); self.c.setFont(FONT_R,7.7)
        self.c.drawCentredString(W/2,self.y,rtl(text)); self.y-=14
    def finish(self): self.c.showPage()

